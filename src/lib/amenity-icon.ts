// Amenities are free text typed in the admin ("Solar Street Light", "30ft Tar
// Road", "CCTV Camera"…), so match on keywords. First match wins: the more
// specific patterns come first.
const RULES: [RegExp, LucideIcon][] = [
  [/solar/i, SunMedium],
  [/cctv|camera|surveillance/i, Cctv],
  [/security|gated/i, ShieldCheck],
  [/street ?light|light/i, Lightbulb],
  [/compound|wall/i, BrickWall],
  [/fenc/i, Fence],
  [/arch|entrance|gate/i, Landmark],
  [/walking/i, Footprints],
  [/road|track|street/i, Route],
  [/child|play/i, FerrisWheel],
  [/park|garden/i, Trees],
  [/plant|tree|mango|coconut|teak|guava|amla|mahogany|yield/i, Sprout],
  [/tank|oht/i, Cylinder],
  [/drain/i, Waves],
  [/water|bore|boar|well|pipe|athikadavu/i, Droplets],
  [/eb\b|electric|3-phase|power/i, Zap],
  [/gym/i, Dumbbell],
  [/turf|cricket|ground/i, Goal],
  [/shuttle|court|sport/i, Activity],
  [/club ?house/i, House],
  [/theat/i, Drama],
  [/temple/i, Sparkles],
  [/vaastu|vastu|facing/i, Compass],
  [/loan|bank/i, Banknote],
  [/cab|pickup|transport/i, Car],
  [/gift/i, Gift],
  [/shop|store/i, Store],
  [/maintenance/i, Wrench],
  [/dtcp|rera|approv/i, FileCheck2],
];

export function amenityIcon(name: string): LucideIcon {
  return RULES.find(([re]) => re.test(name))?.[1] ?? CheckCircle2;
}
