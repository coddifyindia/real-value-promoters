// Generates supabase/seed.sql from src/data/seed-properties.json.
// Usage: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const properties = JSON.parse(
  readFileSync(new URL("../src/data/seed-properties.json", import.meta.url), "utf8"),
);

const str = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(str).join(", ")}]::text[]`;

const columns = [
  "legacy_id", "slug", "name", "location", "city", "type", "price_label", "price_from",
  "description", "amenities", "images", "contact_name", "contact_phones", "youtube_id",
  "map_embed_url", "instagram_url", "featured", "published", "sort_order",
];

const rows = properties.map((p) =>
  [
    p.legacy_id ?? "null", str(p.slug), str(p.name), str(p.location), str(p.city),
    `${str(p.type)}::public.property_type`, str(p.price_label), p.price_from ?? "null",
    str(p.description), arr(p.amenities), arr(p.images), str(p.contact_name),
    arr(p.contact_phones), str(p.youtube_id), str(p.map_embed_url), str(p.instagram_url),
    p.featured, p.published, p.sort_order,
  ].join(",\n    "),
);

const sql = `-- Generated by scripts/generate-seed.mjs. Re-running is safe: existing slugs are skipped.
insert into public.properties (
  ${columns.join(", ")}
) values
  (
    ${rows.join("\n  ),\n  (\n    ")}
  )
on conflict (slug) do nothing;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${properties.length} properties`);
